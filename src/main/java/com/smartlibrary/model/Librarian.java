package com.smartlibrary.model;
public class Librarian {
    private int libId;
    private String libName;
    private String libPassword;
    public int getLibId() { return libId; }
    public void setLibId(int libId) { this.libId = libId; }
    public String getLibName() { return libName; }
    public void setLibName(String libName) { this.libName = libName; }
    public String getLibPassword() { return libPassword; }
    public void setLibPassword(String libPassword) { this.libPassword = libPassword; }
}
